// Helper functions
export const getPendingKYC = () => {
  return mockKYCQueue.filter((kyc) => kyc.status === 'pending' || kyc.status === 'under_review');
};

export const getKYCByStatus = (status: KYCSubmission['status']) => {
  return mockKYCQueue.filter((kyc) => kyc.status === status);
};

export const getOpenFraudAlerts = () => {
  return mockFraudAlerts.filter((alert) => alert.status === 'open' || alert.status === 'investigating');
};

export const getFraudAlertsBySeverity = (severity: FraudAlert['severity']) => {
  return mockFraudAlerts.filter((alert) => alert.severity === severity);
};
